function formatPrice(num) {
  return num.toLocaleString('ru-RU') + ' ₸';
}

function getSessionKey(dayId, filmId, time) {
  return `${dayId}__${filmId}__${time}`;
}

function getOccupiedSeats(dayId, filmId, time) {
  const key = getSessionKey(dayId, filmId, time);
  if (!state.occupiedMap[key]) {
    const seed = (filmId.length + time.charCodeAt(1)) % 5;
    const baseBusy = [
      ['3-5', '3-6', '4-4', '4-5', '6-6', '6-7'],
      ['2-4', '2-5', '5-5', '5-6', '8-2'],
      ['4-6', '4-7', '5-3', '5-4', '7-5', '7-6'],
      ['3-3', '3-4', '6-4', '6-5', '8-3'],
      ['2-6', '2-7', '4-5', '4-6', '7-4']
    ];
    state.occupiedMap[key] = baseBusy[seed];
    localStorage.setItem(STORAGE_KEYS.OCCUPIED, JSON.stringify(state.occupiedMap));
  }
  return state.occupiedMap[key];
}


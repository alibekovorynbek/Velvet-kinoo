function openBookingModal(filmId, time) {
  const film = FILMS_2026.find(f => f.id === filmId);
  if (!film) return;

  state.booking.filmId = filmId;
  state.booking.time = time;
  state.booking.selectedSeats = [];
  state.booking.promoApplied = false;

  document.getElementById('promoInput').value = '';
  document.getElementById('promoStatus').textContent = '';

  const dayObj = DAYS.find(d => d.id === state.selectedDay);
  document.getElementById('modalFilmTitle').textContent = film.title;
  document.getElementById('modalSessionMeta').textContent = `ЗАЛ №1 · ${film.format} · ${dayObj.full}`;
  document.getElementById('checkoutDateBadge').textContent = `${dayObj.short.split('·').pop().trim()} · ${time}`;

  const switcher = document.getElementById('modalTimeSwitcher');
  switcher.innerHTML = film.sessions.map(t => `
    <button class="switch-pill ${t === time ? 'active' : ''}" data-switchtime="${t}">
      ${t}
    </button>
  `).join('');

  switcher.querySelectorAll('.switch-pill').forEach(btn => {
    btn.addEventListener('click', () => openBookingModal(filmId, btn.dataset.switchtime));
  });

  startBookingTimer();
  renderHallSeats();
  renderCheckoutPanel();
  document.getElementById('bookingModal').classList.remove('hidden');
}

function startBookingTimer() {
  clearInterval(state.booking.timerInterval);
  state.booking.timerSeconds = 899;
  const timerEl = document.getElementById('bookingTimer');

  const updateTick = () => {
    const m = String(Math.floor(state.booking.timerSeconds / 60)).padStart(2, '0');
    const s = String(state.booking.timerSeconds % 60).padStart(2, '0');
    timerEl.textContent = `${m}:${s}`;
    if (state.booking.timerSeconds <= 0) {
      clearInterval(state.booking.timerInterval);
      state.booking.selectedSeats = [];
      renderHallSeats();
      renderCheckoutPanel();
    }
    state.booking.timerSeconds--;
  };

  updateTick();
  state.booking.timerInterval = setInterval(updateTick, 1000);
}

function renderHallSeats() {
  const { filmId, time, selectedSeats } = state.booking;
  const occupied = getOccupiedSeats(state.selectedDay, filmId, time);
  const grid = document.getElementById('seatsGrid');
  const hint = document.getElementById('seatHoverHint');

  let html = '';
  for (let row = 1; row <= 8; row++) {
    const isVip = row === 8;
    const isComfort = row >= 5 && row <= 7;
    const cols = isVip ? 5 : 10;
    const price = isVip ? 4500 : isComfort ? 3000 : 2200;
    const typeName = isVip ? 'Velvet LoveSeat (диван на двоих)' : isComfort ? 'Comfort' : 'Standard';

    html += `<div class="seat-row"><span class="row-num">${String(row).padStart(2, '0')}</span>`;
    for (let col = 1; col <= cols; col++) {
      const seatId = `${row}-${col}`;
      const isBusy = occupied.includes(seatId);
      const isSelected = selectedSeats.some(s => s.id === seatId);
      const label = isVip ? `VIP ${col}` : col;

      html += `
        <button type="button"
          class="seat ${isComfort ? 'seat--comfort' : ''} ${isVip ? 'seat--vip' : ''} ${isBusy ? 'seat--occupied' : ''} ${isSelected ? 'seat--selected' : ''}"
          data-seatid="${seatId}"
          data-row="${row}"
          data-col="${col}"
          data-price="${price}"
          data-typename="${typeName}"
          ${isBusy ? 'disabled' : ''}>
          ${label}
        </button>
      `;
    }
    html += `</div>`;
  }
  grid.innerHTML = html;

  grid.querySelectorAll('.seat:not(.seat--occupied)').forEach(btn => {
    btn.addEventListener('mouseenter', () => {
      hint.textContent = `Ряд ${btn.dataset.row}, место ${btn.dataset.col} — ${btn.dataset.typename} (${formatPrice(Number(btn.dataset.price))})`;
    });
    btn.addEventListener('mouseleave', () => {
      hint.textContent = 'Наведите на кресло, чтобы увидеть ряд, место и тариф';
    });
    btn.addEventListener('click', () => toggleSeatSelection(btn.dataset));
  });
}

function toggleSeatSelection(ds) {
  const idx = state.booking.selectedSeats.findIndex(s => s.id === ds.seatid);
  if (idx > -1) {
    state.booking.selectedSeats.splice(idx, 1);
  } else {
    if (state.booking.selectedSeats.length >= 6) {
      alert('За один заказ можно выбрать не более 6 мест.');
      return;
    }
    state.booking.selectedSeats.push({
      id: ds.seatid,
      row: Number(ds.row),
      col: Number(ds.col),
      price: Number(ds.price),
      typeName: ds.typename
    });
  }
  renderHallSeats();
  renderCheckoutPanel();
}

function renderCheckoutPanel() {
  const listEl = document.getElementById('selectedSeatsList');
  const seats = state.booking.selectedSeats;

  if (!seats.length) {
    listEl.innerHTML = `<p class="empty-note">Выберите от 1 до 6 мест на схеме зала слева.</p>`;
  } else {
    listEl.innerHTML = seats.map(s => `
      <div class="selected-item">
        <span>Ряд ${s.row}, Место ${s.col} (${s.typeName.split(' ')[0]})</span>
        <span>
          ${formatPrice(s.price)}
          <button type="button" class="remove-seat-btn" data-remove="${s.id}">✕</button>
        </span>
      </div>
    `).join('');

    listEl.querySelectorAll('[data-remove]').forEach(btn => {
      btn.addEventListener('click', () => {
        state.booking.selectedSeats = state.booking.selectedSeats.filter(x => x.id !== btn.dataset.remove);
        renderHallSeats();
        renderCheckoutPanel();
      });
    });
  }

  let subtotal = seats.reduce((sum, s) => sum + s.price, 0);
  if (state.booking.promoApplied) {
    subtotal = Math.round(subtotal * 0.85);
  }
  document.getElementById('totalPriceLabel').textContent = formatPrice(subtotal);

  const userBox = document.getElementById('checkoutUserBox');
  if (state.currentUser) {
    userBox.innerHTML = `
      <div><strong>Зритель:</strong> ${state.currentUser.name}</div>
      <div style="font-size:11px; color:#555;">Билет придёт в кабинет (${state.currentUser.email})</div>
    `;
  } else {
    userBox.innerHTML = `
      <div><strong>Быстрая регистрация для билета:</strong></div>
      <div class="inline-reg-grid">
        <input type="text" id="quickRegName" placeholder="Ваше имя" />
        <input type="email" id="quickRegEmail" placeholder="Email для билета" />
      </div>
    `;
  }

  document.getElementById('confirmPurchaseBtn').disabled = seats.length === 0;
}


function refundTicket(code) {
  const idx = state.tickets.findIndex(t => t.code === code);
  if (idx === -1) return;
  const ticket = state.tickets[idx];

  const occupied = getOccupiedSeats(ticket.dayId, ticket.filmId, ticket.time);
  const seatIdsToFree = ticket.seats.map(s => s.id);
  const key = getSessionKey(ticket.dayId, ticket.filmId, ticket.time);
  state.occupiedMap[key] = occupied.filter(id => !seatIdsToFree.includes(id));
  localStorage.setItem(STORAGE_KEYS.OCCUPIED, JSON.stringify(state.occupiedMap));

  state.tickets.splice(idx, 1);
  localStorage.setItem(STORAGE_KEYS.TICKETS, JSON.stringify(state.tickets));

  updateTicketsBadge();
  renderTicketsView();
  renderFeaturedAndTimetable();
}


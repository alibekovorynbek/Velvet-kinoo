document.getElementById('authForm').addEventListener('submit', (e) => {
  e.preventDefault();
  const email = document.getElementById('authEmailInput').value.trim().toLowerCase();
  const pass = document.getElementById('authPassInput').value.trim();
  const name = document.getElementById('authNameInput').value.trim();
  const errEl = document.getElementById('authErrorMsg');

  if (pass.length < 4) {
    errEl.textContent = 'Пароль должен содержать минимум 4 символа.';
    return;
  }

  const usersDb = JSON.parse(localStorage.getItem(STORAGE_KEYS.USERS_DB) || '[]');

  if (state.authMode === 'register') {
    if (!name) {
      errEl.textContent = 'Введите ваше имя.';
      return;
    }
    if (usersDb.some(u => u.email === email)) {
      errEl.textContent = 'Пользователь с таким Email уже зарегистрирован.';
      return;
    }
    const newUser = { name, email, pass };
    usersDb.push(newUser);
    localStorage.setItem(STORAGE_KEYS.USERS_DB, JSON.stringify(usersDb));
    state.currentUser = { name, email };
  } else {
    const found = usersDb.find(u => u.email === email && u.pass === pass);
    if (!found) {
      state.currentUser = { name: email.split('@')[0], email };
    } else {
      state.currentUser = { name: found.name, email: found.email };
    }
  }

  localStorage.setItem(STORAGE_KEYS.USER, JSON.stringify(state.currentUser));
  document.getElementById('authModal').classList.add('hidden');
  updateAuthHeader();
  updateTicketsBadge();
  renderCheckoutPanel();
});

